const DICTS: Record<Lang, Dict> = { zh, en };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("luno.lang");
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== "undefined" && !navigator.language.toLowerCase().startsWith("zh") ? "en" : "zh";
}

export const useLang = create<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>((set) => {
  const lang = initialLang();
  return {
    lang,
    t: DICTS[lang],
    setLang: (l) => {
      try {
        localStorage.setItem("luno.lang", l);
      } catch {
        /* ignore */
      }
      document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
      set({ lang: l, t: DICTS[l] });
    },
  };
});

export const useT = () => useLang((s) => s.t);
export const getT = () => useLang.getState().t;
